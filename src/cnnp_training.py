# Define the model architecture
class ConvBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size, padding=0):
        super(ConvBlock, self).__init__()
        self.conv1 = nn.Conv2d(in_channels, out_channels, kernel_size, padding=padding)
        self.act = nn.LeakyReLU(negative_slope=0.2)
        self.conv2 = nn.Conv2d(out_channels, out_channels, kernel_size, padding=padding)

    def forward(self, x):
        x = self.conv1(x)
        x = self.act(x)
        x = self.conv2(x)
        return x

class CNNP(nn.Module):
    def __init__(self):
        super(CNNP, self).__init__()

        # Feature Extraction Step (Parallel ConvBlocks)
        self.branch1 = ConvBlock(1, 32, kernel_size=3, padding=1)  # 3x3 receptive field
        self.branch2 = ConvBlock(1, 32, kernel_size=5, padding=2)  # 5x5 receptive field
        self.branch3 = ConvBlock(1, 32, kernel_size=7, padding=3)  # 7x7 receptive field

        # Image Prediction Step (Sequential ConvBlocks)
        self.pred_block1 = ConvBlock(32, 32, kernel_size=3, padding=1)
        self.pred_block2 = ConvBlock(32, 1, kernel_size=3, padding=1)

    def forward(self, x):
        # Feature extraction through parallel branches
        feat1 = self.branch1(x)
        feat2 = self.branch2(x)
        feat3 = self.branch3(x)

        # Aggregation (element-wise sum)
        aggregated = feat1 + feat2 + feat3

        # Image prediction
        x = self.pred_block1(aggregated)
        x = self.pred_block2(x)

        return x

# Define utility functions
def load_and_preprocess_image(image_path, target_size=(512, 512)):
    """
    Load an image, convert to grayscale, and resize to target size
    """
    img = Image.open(image_path).convert('L')  # Convert to grayscale
    img = img.resize(target_size)
    img_array = np.array(img)
    return img_array

def partition_image(image_array):
    """
    Partition image into "Cross" and "Dot" sets
    Cross set: pixels at positions where row+column is even
    Dot set: pixels at positions where row+column is odd
    """
    height, width = image_array.shape
    cross_set = np.zeros_like(image_array)
    dot_set = np.zeros_like(image_array)

    for i in range(height):
        for j in range(width):
            if (i + j) % 2 == 0:  # Cross set (row+column is even)
                cross_set[i, j] = image_array[i, j]
            else:  # Dot set (row+column is odd)
                dot_set[i, j] = image_array[i, j]

    return cross_set, dot_set

# Define dataset class
class ImageNetSampleDataset(Dataset):
    def __init__(self, root_dir, transform=None, target_size=(512,512)):
        self.root_dir    = root_dir
        self.transform   = transform
        self.target_size = target_size

        # walk through all subdirs and collect image paths
        self.image_files = []
        for subdir, _, files in os.walk(self.root_dir):
            for fname in files:
                if fname.lower().endswith(('.jpg', '.jpeg', '.png')):
                    self.image_files.append(os.path.join(subdir, fname))

        if len(self.image_files) == 0:
            raise RuntimeError(f"No images found under {self.root_dir}")

    def __len__(self):
        return len(self.image_files)

    def __getitem__(self, idx):
        img_path = os.path.join(self.root_dir, self.image_files[idx])
        image = load_and_preprocess_image(img_path, self.target_size)

        # Partition into Cross and Dot sets
        cross_set, dot_set = partition_image(image)

        # Convert to tensors and normalize to [0, 1]
        cross_tensor = torch.from_numpy(cross_set).float() / 255.0
        dot_tensor = torch.from_numpy(dot_set).float() / 255.0

        # Add channel dimension
        cross_tensor = cross_tensor.unsqueeze(0)
        dot_tensor = dot_tensor.unsqueeze(0)

        return cross_tensor, dot_tensor

# Download ImageNet sample dataset
def download_imagenet_sample(output_dir='/content/drive/MyDrive'):
    """
    Download the ImageNet sample dataset
    """
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)

    url = "https://github.com/EliSchwartz/imagenet-sample-images/archive/master.zip"
    print(f"Downloading ImageNet sample images from {url}...")

    response = requests.get(url)
    z = zipfile.ZipFile(io.BytesIO(response.content))
    z.extractall(output_dir)

    print(f"Downloaded and extracted to {output_dir}")
    return os.path.join(output_dir, "imagenet-sample-images-master")

# Training function
def train_cnnp(model, train_loader, val_loader=None, num_epochs=50, learning_rate=1e-4, weight_decay=1e-3, device='cuda'):
    """
    Train the CNN predictor
    """
    model = model.to(device)
    criterion = nn.MSELoss()
    optimizer = optim.Adam(model.parameters(), lr=learning_rate, weight_decay=weight_decay)

    train_losses = []
    val_losses = []

    for epoch in range(num_epochs):
        # Training
        model.train()
        running_loss = 0.0

        for cross_set, dot_set in tqdm(train_loader, desc=f"Epoch {epoch+1}/{num_epochs}"):
            cross_set = cross_set.to(device)
            dot_set = dot_set.to(device)

            # Forward pass
            outputs = model(cross_set)
            loss = criterion(outputs, dot_set)

            # Backward and optimize
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            running_loss += loss.item()

        epoch_loss = running_loss / len(train_loader)
        train_losses.append(epoch_loss)

        print(f"Epoch [{epoch+1}/{num_epochs}], Train Loss: {epoch_loss:.6f}")

        # Validation
        if val_loader is not None:
            model.eval()
            val_loss = 0.0

            with torch.no_grad():
                for cross_set, dot_set in val_loader:
                    cross_set = cross_set.to(device)
                    dot_set = dot_set.to(device)

                    outputs = model(cross_set)
                    loss = criterion(outputs, dot_set)

                    val_loss += loss.item()

            val_loss = val_loss / len(val_loader)
            val_losses.append(val_loss)

            print(f"Epoch [{epoch+1}/{num_epochs}], Validation Loss: {val_loss:.6f}")


    # Save the trained model
    os.makedirs('./saved_models', exist_ok=True)
    torch.save(model.state_dict(), '/content/drive/MyDrive/cnnp_model.pth')
    return model, train_losses, val_losses

# Main training code
def main():
    # Set device
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"Using device: {device}")

    # Download ImageNet sample dataset
    data_dir = download_imagenet_sample()
    print("dataset and data loaders")
    # Create dataset and data loaders
    dataset = ImageNetSampleDataset(data_dir)
    print("split dataset")
    # Split dataset into training and validation sets (90% train, 10% val)
    train_size = int(0.9 * len(dataset))
    val_size = len(dataset) - train_size
    train_dataset, val_dataset = torch.utils.data.random_split(dataset, [train_size, val_size])

    train_loader = DataLoader(train_dataset, batch_size=4, shuffle=True, num_workers=2)
    val_loader = DataLoader(val_dataset, batch_size=4, shuffle=False, num_workers=2)

    # Initialize model
    model = CNNP()

    # Train model
    trained_model, train_losses, val_losses = train_cnnp(
        model=model,
        train_loader=train_loader,
        val_loader=val_loader,
        num_epochs=50,
        learning_rate=1e-4,
        weight_decay=1e-3,
        device=device
    )

    print("Training completed!")

# Run the main function
main()

