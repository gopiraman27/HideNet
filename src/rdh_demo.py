# Define the model architecture
class ConvBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size, padding=0):
        super(ConvBlock, self).__init__()
        self.conv1 = nn.Conv2d(in_channels, out_channels, kernel_size, padding=padding)
        self.act = nn.LeakyReLU(negative_slope=0.2)
        self.conv2 = nn.Conv2d(out_channels, out_channels, kernel_size, padding=padding)

    def forward(self, x):
        x = self.conv1(x)
        x = self.act(x)
        x = self.conv2(x)
        return x

class CNNP(nn.Module):
    def __init__(self):
        super(CNNP, self).__init__()

        # Feature Extraction Step (Parallel ConvBlocks)
        self.branch1 = ConvBlock(1, 32, kernel_size=3, padding=1)  # 3x3 receptive field
        self.branch2 = ConvBlock(1, 32, kernel_size=5, padding=2)  # 5x5 receptive field
        self.branch3 = ConvBlock(1, 32, kernel_size=7, padding=3)  # 7x7 receptive field

        # Image Prediction Step (Sequential ConvBlocks)
        self.pred_block1 = ConvBlock(32, 32, kernel_size=3, padding=1)
        self.pred_block2 = ConvBlock(32, 1, kernel_size=3, padding=1)

    def forward(self, x):
        # Feature extraction through parallel branches
        feat1 = self.branch1(x)
        feat2 = self.branch2(x)
        feat3 = self.branch3(x)

        # Aggregation (element-wise sum)
        aggregated = feat1 + feat2 + feat3

        # Image prediction
        x = self.pred_block1(aggregated)
        x = self.pred_block2(x)

        return x

# Define utility functions
def load_and_preprocess_image(image_path, target_size=(512, 512)):
    """
    Load an image, convert to grayscale, and resize to target size
    """
    img = Image.open(image_path).convert('L')  # Convert to grayscale
    img = img.resize(target_size)
    img_array = np.array(img)
    return img_array

def partition_image(image_array):
    """
    Partition image into "Cross" and "Dot" sets
    Cross set: pixels at positions where row+column is even
    Dot set: pixels at positions where row+column is odd
    """
    height, width = image_array.shape
    cross_set = np.zeros_like(image_array)
    dot_set = np.zeros_like(image_array)

    for i in range(height):
        for j in range(width):
            if (i + j) % 2 == 0:  # Cross set (row+column is even)
                cross_set[i, j] = image_array[i, j]
            else:  # Dot set (row+column is odd)
                dot_set[i, j] = image_array[i, j]

    return cross_set, dot_set

def reconstruct_image(cross_set_image, dot_set_image):
    """
    Combine the "Cross" and "Dot" sets to reconstruct the full image
    """
    return cross_set_image + dot_set_image

def prepare_for_cnn(image_array):
    """
    Convert numpy array to PyTorch tensor with proper dimensions for CNN input
    """
    # Convert to float and normalize to [0, 1]
    img_tensor = torch.from_numpy(image_array).float() / 255.0
    # Add batch and channel dimensions: (H, W) -> (1, 1, H, W)
    img_tensor = img_tensor.unsqueeze(0).unsqueeze(0)
    return img_tensor

def tensor_to_numpy(tensor):
    """
    Convert PyTorch tensor to numpy array, removing batch and channel dimensions
    """
    # (1, 1, H, W) -> (H, W)
    return tensor.squeeze().detach().cpu().numpy()

import numpy as np

def embed_pee(original_pixels, predicted_pixels, data_bits):
    orig = original_pixels.astype(np.int16)
    pred = np.round(predicted_pixels).astype(np.int16)
    errors = orig - pred
    flat_orig = orig.flatten()
    flat_pred = pred.flatten()
    valid_idxs = np.where(flat_orig > 0)[0]
    flat_err = flat_orig[valid_idxs] - flat_pred[valid_idxs]
    emb_ok = (flat_pred[valid_idxs] + 2 * flat_err + 1 <= 255) & (flat_pred[valid_idxs] + 2 * flat_err >= 0)
    if emb_ok.sum() < len(data_bits):
        raise ValueError(f"PEE capacity {emb_ok.sum()} bits < payload {len(data_bits)} bits")
    flat_mod = flat_err.copy()
    location_map = []
    bit_idx = 0
    for i, e in enumerate(flat_err):
        if emb_ok[i] and bit_idx < len(data_bits):
            flat_mod[i] = 2 * e + int(data_bits[bit_idx])
            location_map.append((i, 0))
            bit_idx += 1
        else:
            location_map.append((i, 1))
    mod_errors_flat = errors.flatten()
    for j, idx in enumerate(valid_idxs):
        mod_errors_flat[idx] = flat_mod[j]
    mod_errors = mod_errors_flat.reshape(orig.shape)
    wm = pred + mod_errors
    wm = np.clip(wm, 0, 255).astype(np.uint8)
    return wm, {'valid_idxs': valid_idxs, 'location_map': location_map, 'embedded_bits': bit_idx}

def extract_pee(watermarked_pixels, predicted_pixels, overhead):
    wm = watermarked_pixels.astype(np.int16)
    pred = np.round(predicted_pixels).astype(np.int16)
    w_errors_flat = (wm - pred).flatten()
    valid_idxs = overhead['valid_idxs']
    location_map = overhead['location_map']
    emb_bits = overhead['embedded_bits']
    extracted = []
    rec_errors_flat = w_errors_flat.copy()
    count = 0
    for pos, is_over in location_map:
        if count >= emb_bits:
            break
        idx = valid_idxs[pos]
        if is_over == 0:
            e_p = w_errors_flat[idx]
            extracted.append(int(e_p & 1))
            rec_errors_flat[idx] = e_p // 2
            count += 1
    rec_errors = rec_errors_flat.reshape(wm.shape)
    rec_pixels = pred + rec_errors
    rec_pixels = np.clip(rec_pixels, 0, 255).astype(np.uint8)
    return np.array(extracted), rec_pixels

def embed_hs(original_pixels, predicted_pixels, data_bits):
    orig = original_pixels.astype(np.int16)
    pred = np.round(predicted_pixels).astype(np.int16)
    errors = orig - pred
    flat_orig = orig.flatten()
    flat_pred = pred.flatten()
    valid_idxs = np.where(flat_orig > 0)[0]
    flat_err = flat_orig[valid_idxs] - flat_pred[valid_idxs]
    unique, counts = np.unique(flat_err, return_counts=True)
    hist = dict(zip(unique, counts))
    peak = max(hist, key=hist.get)
    zeros = [e for e in unique if e != peak]
    zero = min(zeros, key=lambda e: hist[e]) if zeros else (peak + 1 if peak + 1 <= flat_err.max() else peak - 1)
    if hist.get(peak, 0) < len(data_bits):
        raise ValueError(f"HS capacity {hist.get(peak, 0)} bits < payload {len(data_bits)} bits")
    shift = 1 if zero > peak else -1
    flat_mod = flat_err.copy()
    bit_idx = 0
    for i, e in enumerate(flat_err):
        if e == peak and bit_idx < len(data_bits):
            flat_mod[i] = peak + shift if int(data_bits[bit_idx]) == 1 else peak
            bit_idx += 1
        elif (shift == 1 and peak < e <= zero) or (shift == -1 and zero <= e < peak):
            flat_mod[i] = e + shift
    mod_errors_flat = errors.flatten()
    for j, idx in enumerate(valid_idxs):
        mod_errors_flat[idx] = flat_mod[j]
    wm = pred + mod_errors_flat.reshape(orig.shape)
    wm = np.clip(wm, 0, 255).astype(np.uint8)
    return wm, {'valid_idxs': valid_idxs, 'embedded_bits': bit_idx, 'peak': peak, 'zero': zero, 'shift': shift}

def extract_hs(watermarked_pixels, predicted_pixels, overhead):
    wm = watermarked_pixels.astype(np.int16)
    pred = np.round(predicted_pixels).astype(np.int16)
    w_errors_flat = (wm - pred).flatten()
    valid_idxs = overhead['valid_idxs']
    emb_bits = overhead['embedded_bits']
    peak = overhead['peak']
    zero = overhead['zero']
    shift = overhead['shift']
    extracted = []
    rec_errors_flat = w_errors_flat.copy()
    count = 0
    for idx in valid_idxs:
        if count >= emb_bits:
            break
        e = w_errors_flat[idx]
        if e == peak:
            extracted.append(0)
            rec_errors_flat[idx] = peak
            count += 1
        elif e == peak + shift:
            extracted.append(1)
            rec_errors_flat[idx] = peak
            count += 1
        elif (shift == 1 and peak < e <= zero) or (shift == -1 and zero <= e < peak):
            rec_errors_flat[idx] = e - shift
    rec_pixels = pred + rec_errors_flat.reshape(wm.shape)
    rec_pixels = np.clip(rec_pixels, 0, 255).astype(np.uint8)
    return np.array(extracted), rec_pixels

# Define main embedding and extraction functions
def embed_image_twostage(image_path_or_array, data_W1, data_W2, cnn_model, method='pee'):
    """
    Two-stage embedding process
    """
    # Load and preprocess image if path is provided
    if isinstance(image_path_or_array, str):
        original_image = load_and_preprocess_image(image_path_or_array)
    else:
        original_image = image_path_or_array

    # Partition into Cross and Dot sets
    I_C, I_D = partition_image(original_image)

    # Prepare Cross set for CNN input
    I_C_tensor = prepare_for_cnn(I_C)
    # figure out the device your model is on
    device = next(cnn_model.parameters()).device

    # move the input onto that device
    I_C_tensor = I_C_tensor.to(device)

    # Step 1: Predict Dot set from Cross set
    cnn_model.eval()
    with torch.no_grad():
        tilde_I_D_tensor = cnn_model(I_C_tensor)

    # Convert prediction back to numpy array
    tilde_I_D = tensor_to_numpy(tilde_I_D_tensor) * 255.0

    # Step 2: Embed W1 into Dot set
    if method == 'pee':
        I_DW, overhead1 = embed_pee(I_D, tilde_I_D, data_W1)
    else:  # method == 'hs'
        I_DW, overhead1 = embed_hs(I_D, tilde_I_D, data_W1)

    # Step 3: Predict Cross set from watermarked Dot set
    I_DW_tensor = prepare_for_cnn(I_DW)
    # figure out the device your model is on
    device = next(cnn_model.parameters()).device

    # move the input onto that device
    I_DW_tensor = I_DW_tensor.to(device)

    with torch.no_grad():
        tilde_I_C_tensor = cnn_model(I_DW_tensor)

    # Convert prediction back to numpy array
    tilde_I_C = tensor_to_numpy(tilde_I_C_tensor) * 255.0

    # Step 4: Embed W2 into Cross set
    if method == 'pee':
        I_CW, overhead2 = embed_pee(I_C, tilde_I_C, data_W2)
    else:  # method == 'hs'
        I_CW, overhead2 = embed_hs(I_C, tilde_I_C, data_W2)

    # Step 5: Reconstruct watermarked image
    I_W = reconstruct_image(I_CW, I_DW)

    return I_W, overhead1, overhead2

def extract_image_twostage(watermarked_image_path_or_array, cnn_model, overhead1, overhead2, method='pee'):
    """
    Two-stage extraction process
    """
    # Load and preprocess image if path is provided
    if isinstance(watermarked_image_path_or_array, str):
        I_W = load_and_preprocess_image(watermarked_image_path_or_array)
    else:
        I_W = watermarked_image_path_or_array

    # Partition into watermarked Cross and Dot sets
    I_CW, I_DW = partition_image(I_W)

    # Step 1: Predict Cross set from watermarked Dot set
    I_DW_tensor = prepare_for_cnn(I_DW)
    # figure out the device your model is on
    device = next(cnn_model.parameters()).device

    # move the input onto that device
    I_DW_tensor = I_DW_tensor.to(device)

    cnn_model.eval()
    with torch.no_grad():
        tilde_I_C_tensor = cnn_model(I_DW_tensor)

    # Convert prediction back to numpy array
    tilde_I_C = tensor_to_numpy(tilde_I_C_tensor) * 255.0

    # Step 2: Extract W2 from watermarked Cross set and recover original Cross set
    if method == 'pee':
        extracted_W2, recovered_I_C = extract_pee(I_CW, tilde_I_C, overhead2)
    else:  # method == 'hs'
        extracted_W2, recovered_I_C = extract_hs(I_CW, tilde_I_C, overhead2)

    # Step 3: Predict Dot set from recovered Cross set
    recovered_I_C_tensor = prepare_for_cnn(recovered_I_C)
    recovered_I_C_tensor = recovered_I_C_tensor.to(device)
    with torch.no_grad():
        tilde_I_D_tensor = cnn_model(recovered_I_C_tensor)

    # Convert prediction back to numpy array
    tilde_I_D = tensor_to_numpy(tilde_I_D_tensor) * 255.0

    # Step 4: Extract W1 from watermarked Dot set and recover original Dot set
    if method == 'pee':
        extracted_W1, recovered_I_D = extract_pee(I_DW, tilde_I_D, overhead1)
    else:  # method == 'hs'
        extracted_W1, recovered_I_D = extract_hs(I_DW, tilde_I_D, overhead1)

    # Step 5: Reconstruct original image
    reconstructed_image = reconstruct_image(recovered_I_C, recovered_I_D)

    return reconstructed_image, extracted_W1, extracted_W2

# Define evaluation metrics
def calculate_mse(image1, image2):
    """
    Calculate Mean Squared Error between two images
    """
    if image1.shape != image2.shape:
        raise ValueError("Images must have the same dimensions")

    mse = np.mean((image1.astype(np.float32) - image2.astype(np.float32)) ** 2)
    return mse

def calculate_psnr(image1, image2, max_pixel_value=255):
    """
    Calculate Peak Signal-to-Noise Ratio between two images
    """
    mse = calculate_mse(image1, image2)
    if mse == 0:
        return float('inf')

    psnr = 20 * np.log10(max_pixel_value / np.sqrt(mse))
    return psnr

def calculate_embedding_rate(embedded_bits, image_size):
    """
    Calculate embedding rate in bits per pixel (bpp)
    """
    total_pixels = image_size[0] * image_size[1]
    bpp = embedded_bits / total_pixels
    return bpp

